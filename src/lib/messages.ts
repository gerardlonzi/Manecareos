export function localizeMessage(message: string | null | undefined, locale: Locale): string {
  const msg = message ?? "";
  if (locale === "fr" || !msg) return msg;
  const exact = DICT[msg];
  if (exact) return exact;
  for (const [re, fn] of PATTERNS) {
    const m = msg.match(re);
    if (m) return fn(m);
  }
  return msg;
}

/** Libellé d'un événement du journal, dans la langue choisie. */
export function describeActivity(log: { event_type: string; description: string }, locale: Locale): string {
  return localizeMessage(log.description, locale);
}
